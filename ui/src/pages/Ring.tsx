function TrialTab({ isSecWrangler, getFreshJWT }: {
  isSecWrangler: boolean;
  getFreshJWT: () => Promise<string | null>;
}) {
  const [serviceName, setServiceName] = useState('');
  const [yaml, setYaml] = useState('');
  const [running, setRunning] = useState(false);
  const [result, setResult] = useState<ContractSuite | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [expandedTest, setExpandedTest] = useState<string | null>(null);

  async function runTrial() {
    if (!serviceName.trim() || !yaml.trim()) return;
    setRunning(true); setResult(null); setError(null);
    try {
      const freshJwt = await getFreshJWT();
      if (!freshJwt) throw new Error('Session expired');
      const res = await fetch(`${GATEWAY}/augur-canis/ring/run`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${freshJwt}` },
        body: JSON.stringify({ service_name: serviceName.trim(), yaml: yaml.trim() }),
      });
      const data = await res.json();
      if (!res.ok) { setError(data.message || `HTTP ${res.status}`); return; }
      setResult(data);
    } catch (e: unknown) {
      setError(e instanceof Error ? e.message : 'Unknown error');
    } finally {
      setRunning(false);
    }
  }

  return (
    <div style={s.body}>
      <div style={s.intro}>
        <div style={s.introTitle}>TRIAL — AD-HOC CONTRACT TEST</div>
        <div style={s.introText}>
          Paste an OpenAPI contract YAML and specify the target Job. AC parses the
          endpoints and runs them over mTLS. Trial runs are recorded in Reports under
          "Ring (Trial)". Use this to verify a contract before it goes into the hardcoded
          suite, or to investigate a suspected regression without touching the code.
        </div>
        {!isSecWrangler && (
          <div style={s.accessDenied}>Trial requires sec-wr4ngler clearance.</div>
        )}
      </div>

      {isSecWrangler && (
        <>
          <div style={s.form}>
            <div style={s.formRow}>
              <div style={s.formGroup}>
                <label style={s.label}>TARGET JOB</label>
                <input
                  style={s.input}
                  placeholder="e.g. signal-clearance"
                  value={serviceName}
                  onChange={e => setServiceName(e.target.value)}
                  disabled={running}
                />
              </div>
              <button
                style={{ ...s.runBtn, opacity: running || !serviceName || !yaml ? 0.5 : 1 }}
                onClick={runTrial}
                disabled={running || !serviceName.trim() || !yaml.trim()}
              >
                {running ? 'Running...' : '> Run Trial'}
              </button>
            </div>
            <div style={s.formGroup}>
              <label style={s.label}>CONTRACT YAML</label>
              <textarea
                style={s.textarea}
                placeholder={`paths:\n  /health:\n    get:\n      summary: Health check\n  /auth/dev/login:\n    post:\n      summary: Dev login`}
                value={yaml}
                onChange={e => setYaml(e.target.value)}
                disabled={running}
                rows={16}
              />
            </div>
          </div>

          {error && (
            <div style={s.bannerErr}>
              <span>✗ {error}</span>
              <button style={s.bannerClose} onClick={() => setError(null)}>x</button>
            </div>
          )}

          {result && (
            <SuiteDetail suite={result} expandedTest={expandedTest} onToggle={setExpandedTest} />
          )}
        </>
      )}
    </div>
  );
}

