function triggerLabel(trigger: string): string {
  switch (trigger) {
    case 'startup':   return 'Startup';
    case 'scheduled': return 'Scheduled';
    case 'on-demand': return 'On-Demand';
    case 'ring':      return 'Ring (Trial)';
    default:          return trigger;
  }
}

function fmtDate(iso: string): string {
  try { return new Date(iso).toLocaleString(); } catch { return iso; }
}

function downloadContractReport(suite: ContractSuite) {
  const ts = new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
  const lines: string[] = [];
  lines.push('='.repeat(70));
  lines.push('  S.E.T.I. — CONTRACT TEST REPORT');
  lines.push(`  Generated: ${ts}`);
  lines.push(`  Run: ${suite.run_id}`);
  lines.push(`  Trigger: ${triggerLabel(suite.trigger)}  Started: ${fmtDate(suite.started_at)}`);
  lines.push(`  Summary: ${suite.passed}/${suite.total} passed, ${suite.failed} failed, ${suite.skipped} skipped  (${suite.duration_ms}ms)`);
  lines.push('='.repeat(70));
  lines.push('');
  for (const test of (suite.results || [])) {
    const isSkipped = test.failure_reason?.startsWith('skip:');
    const icon = isSkipped ? '—' : test.passed ? '✓' : '✗';
    lines.push(`${icon} ${test.test_name}  ${test.actual_status}/${test.expected_status}  ${test.latency_ms}ms`);
    if (!test.passed && test.failure_reason) {
      lines.push(`    Reason: ${test.failure_reason}`);
    }
    if (!test.passed && test.actual_response !== undefined) {
      lines.push(`    Response: ${JSON.stringify(test.actual_response)}`);
    }
  }
  lines.push('');
  lines.push(`Report generated by S.E.T.I. — Search for Erroneous Tessellated Interactions`);
  const now = new Date();
  const datePart = now.toISOString().slice(0, 10);
  const timePart = now.toTimeString().slice(0, 8).replace(/:/g, '-');
  downloadText(lines.join('\n'), `seti-contract-report-${datePart}-${timePart}.txt`);
}

function downloadPlotReport(run: PlotRun) {
  const ts = new Date().toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
  const lines: string[] = [];
  lines.push('='.repeat(70));
  lines.push('  S.E.T.I. — PLOT TEST REPORT');
  lines.push(`  Generated: ${ts}`);
  lines.push(`  Plot: ${run.plot_name || run.plot_id}`);
  lines.push(`  Run: ${run.run_id}  Started: ${fmtDate(run.started_at)}`);
  lines.push(`  Summary: ${run.passed_steps}/${run.total_steps} steps passed, ${run.failed_steps} failed`);
  lines.push(`  Status: ${run.status.toUpperCase()}`);
  lines.push('='.repeat(70));
  lines.push('');
  for (const step of (run.steps || [])) {
    const icon = step.passed ? '✓' : '✗';
    lines.push(`${icon} Step ${step.step_number}: ${step.description}`);
    lines.push(`    status: ${step.actual_status ?? '?'}/${step.expected_status ?? '?'}  latency: ${step.latency_ms ?? 0}ms`);
    if (!step.passed && step.failure_reason) {
      lines.push(`    reason: ${step.failure_reason}`);
    }
  }
  lines.push('');
  lines.push(`Report generated by S.E.T.I. — Search for Erroneous Tessellated Interactions`);
  const now = new Date();
  const datePart = now.toISOString().slice(0, 10);
  const timePart = now.toTimeString().slice(0, 8).replace(/:/g, '-');
  downloadText(lines.join('\n'), `seti-plot-report-${datePart}-${timePart}.txt`);
}

function downloadText(content: string, filename: string) {
  const blob = new Blob([content], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click();
  document.body.removeChild(a); URL.revokeObjectURL(url);
}

