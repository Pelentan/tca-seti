function ReportsTab({ jwt, getFreshJWT, active }: {
  jwt: string | null;
  getFreshJWT: () => Promise<string | null>;
  active: { id: string; label: string };
}) {
  const [contractSuites, setContractSuites] = useState<ContractSuite[]>([]);
  const [plotRuns, setPlotRuns] = useState<PlotRun[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedContract, setSelectedContract] = useState('');
  const [selectedPlot, setSelectedPlot] = useState('');
  const [contractDetail, setContractDetail] = useState<ContractSuite | null>(null);
  const [loadingDetail, setLoadingDetail] = useState(false);
  const [expandedTest, setExpandedTest] = useState<string | null>(null);

  async function authFetch(path: string) {
    const freshJwt = await getFreshJWT();
    if (!freshJwt) throw new Error('Session expired');
    return fetch(`${GATEWAY}${path}`, {
      headers: { Authorization: `Bearer ${freshJwt}` },
    });
  }

  useEffect(() => {
    if (!jwt) return;
    setLoading(true);
    Promise.all([
      authFetch('/augur-canis/contract-suites'),
      authFetch(`/plot-results?application_id=${active.id}&limit=50`),
    ]).then(async ([csRes, prRes]) => {
      if (csRes.ok) { const d = await csRes.json(); setContractSuites(d.suites || []); }
      if (prRes.ok) { const d = await prRes.json(); setPlotRuns(d.runs || []); }
    }).finally(() => setLoading(false));
  }, [jwt, active.id]);

  async function selectContract(runId: string) {
    setSelectedContract(runId);
    setContractDetail(null);
    setExpandedTest(null);
    if (!runId) return;
    setLoadingDetail(true);
    try {
      // Try dedicated endpoint first; fall back to checks/recent for the latest run
      const res = await authFetch(`/augur-canis/contract-suites/${runId}`);
      if (res.ok) {
        setContractDetail(await res.json());
      } else {
        // Fallback: most recent
        const recent = await authFetch('/augur-canis/checks/recent');
        if (recent.ok) {
          const d = await recent.json();
          if (d.run_id === runId) setContractDetail(d);
        }
      }
    } finally {
      setLoadingDetail(false);
    }
  }

  const selectedPlotRun = plotRuns.find(r => r.run_id === selectedPlot) || null;

  return (
    <div style={s.body}>
      <div style={s.intro}>
        <div style={s.introTitle}>REPORTS</div>
        <div style={s.introText}>
          Historical contract and plot test results. Contract tests include scheduled
          runs, on-demand runs, and Ring trials. Plot tests are grouped by constellation.
        </div>
      </div>

      {loading ? <div style={s.empty}>Loading...</div> : (
        <div style={s.reportsCols}>

          {/* ---- Contract Tests ---- */}
          <div style={s.reportsGroup}>
            <div style={s.groupTitle}>CONTRACT TESTS</div>
            {contractSuites.length === 0
              ? <div style={s.empty}>No contract test runs yet.</div>
              : (
                <>
                  <select style={s.select} value={selectedContract}
                    onChange={e => selectContract(e.target.value)}>
                    <option value="">— select a run —</option>
                    {contractSuites.map(suite => (
                      <option key={suite.run_id} value={suite.run_id}>
                        {fmtDate(suite.started_at)} · {triggerLabel(suite.trigger)} · {suite.passed}/{suite.total}{suite.failed > 0 ? ` ✗${suite.failed}` : ' ✓'}
                      </option>
                    ))}
                  </select>

                  {loadingDetail && <div style={s.empty}>Loading detail...</div>}
                  {contractDetail && (
                    <>
                      <div style={{ display: 'flex', justifyContent: 'flex-end', marginBottom: 6 }}>
                        <button style={s.dlBtn} onClick={() => downloadContractReport(contractDetail)}>
                          ↓ Download Report
                        </button>
                      </div>
                      <SuiteDetail suite={contractDetail} expandedTest={expandedTest} onToggle={setExpandedTest} />
                    </>
                  )}
                  {selectedContract && !loadingDetail && !contractDetail && (
                    <div style={s.empty}>Full detail stored in Redis. Only the most recent run is directly fetchable — earlier runs show summary only.</div>
                  )}
                </>
              )}
          </div>

          {/* ---- Plot Tests ---- */}
          <div style={s.reportsGroup}>
            <div style={s.groupTitle}>PLOT TESTS</div>
            {plotRuns.length === 0
              ? <div style={s.empty}>No plot test runs for {active.label}.</div>
              : (
                <>
                  <select style={s.select} value={selectedPlot}
                    onChange={e => setSelectedPlot(e.target.value)}>
                    <option value="">— select a run —</option>
                    {plotRuns.map(run => (
                      <option key={run.run_id} value={run.run_id}>
                        {fmtDate(run.started_at)} · {run.plot_name || run.plot_id} · {run.passed_steps}/{run.total_steps}{run.failed_steps > 0 ? ` ✗${run.failed_steps}` : ' ✓'}
                      </option>
                    ))}
                  </select>

                  {selectedPlotRun && (
                    <>
                      <div style={{ display: 'flex', justifyContent: 'flex-end', marginBottom: 6 }}>
                        <button style={s.dlBtn} onClick={() => downloadPlotReport(selectedPlotRun)}>
                          ↓ Download Report
                        </button>
                      </div>
                      <div style={s.suiteDetail}>
                      <div style={s.suiteHeader}>
                        <span style={s.suiteTitle}>STEPS</span>
                        <span style={{
                          fontSize: 13, fontWeight: 600,
                          color: selectedPlotRun.status === 'passed' ? '#3fb950' : '#f85149',
                        }}>
                          {selectedPlotRun.status === 'passed' ? '✓' : '✗'} {selectedPlotRun.passed_steps}/{selectedPlotRun.total_steps}
                        </span>
                        <span style={{ fontSize: 11, color: '#484f58', flex: 1 }}>
                          {selectedPlotRun.plot_name || selectedPlotRun.plot_id}
                        </span>
                      </div>
                      <div style={s.testList}>
                        {(selectedPlotRun.steps || []).map(step => (
                          <div key={step.step_number}
                            style={{ ...s.testRow, borderLeftColor: step.passed ? '#3fb950' : '#f85149' }}>
                            <div style={{ ...s.testRowHeader, cursor: 'default' }}>
                              <span style={{ color: step.passed ? '#3fb950' : '#f85149', fontSize: 12 }}>
                                {step.passed ? '+' : 'x'}
                              </span>
                              <span style={s.testName}>Step {step.step_number}: {step.description}</span>
                              {step.actual_status !== undefined && (
                                <span style={s.testStatus}>{step.actual_status}/{step.expected_status}</span>
                              )}
                              {step.latency_ms !== undefined && (
                                <span style={s.testLatency}>{step.latency_ms}ms</span>
                              )}
                            </div>
                            {!step.passed && step.failure_reason && (
                              <div style={{ padding: '4px 10px 8px', fontSize: 11, color: '#f85149' }}>
                                {step.failure_reason}
                              </div>
                            )}
                          </div>
                        ))}
                      </div>
                    </div>
                    </>
                  )}
                </>
              )}
          </div>

        </div>
      )}
    </div>
  );
}

