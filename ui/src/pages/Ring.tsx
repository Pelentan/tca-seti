// SuiteDetail — shared between Trial results and Reports contract detail
// ---------------------------------------------------------------------------

function SuiteDetail({ suite, expandedTest, onToggle }: {
  suite: ContractSuite;
  expandedTest: string | null;
  onToggle: (id: string | null) => void;
}) {
  const results = suite.results || [];
  return (
    <div style={s.suiteDetail}>
      <div style={s.suiteHeader}>
        <span style={s.suiteTitle}>RESULTS</span>
        <span style={{ fontSize: 13, fontWeight: 600, color: suite.failed === 0 ? '#3fb950' : '#f85149' }}>
          {suite.failed === 0 ? '✓' : '✗'} {suite.passed}/{suite.total} passed
        </span>
        {suite.skipped > 0 && <span style={{ fontSize: 11, color: '#484f58' }}>{suite.skipped} skipped</span>}
        <span style={{ fontSize: 11, color: '#484f58' }}>{suite.duration_ms}ms</span>
        <span style={s.suiteRunId}>{(suite.run_id || '').slice(-16)}</span>
      </div>
      <div style={s.testList}>
        {results.map(test => {
          const isExpanded = expandedTest === test.request_id;
          const isSkipped = test.failure_reason?.startsWith('skip:');
          const color = isSkipped ? '#484f58' : test.passed ? '#3fb950' : '#f85149';
          const icon = isSkipped ? '—' : test.passed ? '+' : 'x';
          return (
            <div key={test.request_id} style={{ ...s.testRow, borderLeftColor: color }}>
              <div
                style={{ ...s.testRowHeader, cursor: !test.passed && !isSkipped ? 'pointer' : 'default' }}
                onClick={() => !test.passed && !isSkipped && onToggle(isExpanded ? null : test.request_id)}
              >
                <span style={{ color, fontSize: 12, flexShrink: 0 }}>{icon}</span>
                <span style={s.testName}>{test.test_name}</span>
                <span style={s.testStatus}>{test.actual_status}/{test.expected_status}</span>
                <span style={s.testLatency}>{test.latency_ms}ms</span>
                {!test.passed && !isSkipped && (
                  <span style={{ fontSize: 9, color: '#484f58' }}>{isExpanded ? '▲' : '▼'}</span>
                )}
              </div>
              {isExpanded && (
                <div style={s.testDetail}>
                  {test.failure_reason && (
                    <div style={s.detailRow}>
                      <span style={s.detailLabel}>Reason:</span>
                      <span style={{ color: '#f85149', fontSize: 11 }}>{test.failure_reason}</span>
                    </div>
                  )}
                  {test.actual_response !== undefined && (
                    <div style={s.detailRow}>
                      <span style={s.detailLabel}>Response:</span>
                      <pre style={s.detailPre}>{JSON.stringify(test.actual_response, null, 2)}</pre>
                    </div>
                  )}
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}

